"""Evaluate a trained run on its held-out images and record the metrics.

Usage:
    python -m src.evaluate --run inceptionv3_v5000_n6000_e20          # greedy decoding
    python -m src.evaluate --run inceptionv3_v5000_n6000_e20 --beam 3
    python -m src.evaluate --report-only                               # rebuild chart + README

Writes/updates (one row per run + decoding):
    results/metrics.csv, results/comparison.png, results/predictions_<run>.csv
and regenerates the results table in README.md between the RESULTS markers.
Every number comes from this script; nothing is hard-coded.
"""
import argparse
import csv
from pathlib import Path

import numpy as np

from src import config

METRICS = ["BLEU-1", "BLEU-2", "BLEU-3", "BLEU-4", "METEOR", "ROUGE-L", "WER"]
COLUMNS = ["run", "backbone", "vocab", "images", "epochs", "decoding"] + METRICS
README = config.ROOT / "README.md"
MARK_START, MARK_END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _ensure_nltk():
    import nltk

    for res, path in [("wordnet", "corpora/wordnet"), ("omw-1.4", "corpora/omw-1.4")]:
        try:
            nltk.data.find(path)
        except LookupError:
            nltk.download(res, quiet=True)


def compute_metrics(references: list, hypotheses: list) -> dict:
    """references: list (per image) of lists of reference strings; hypotheses: strings.

    BLEU-1..4: corpus BLEU with smoothing (method1).
    METEOR: mean sentence METEOR against all references.
    ROUGE-L: mean of the best F-measure over the references.
    WER: mean of the lowest WER over the references (best-matching reference).
    """
    import jiwer
    from nltk.translate.bleu_score import SmoothingFunction, corpus_bleu
    from nltk.translate.meteor_score import meteor_score
    from rouge_score import rouge_scorer

    _ensure_nltk()
    refs_tok = [[r.split() for r in refs] for refs in references]
    hyps_tok = [h.split() for h in hypotheses]
    smooth = SmoothingFunction().method1
    weights = [(1, 0, 0, 0), (0.5, 0.5, 0, 0), (1 / 3, 1 / 3, 1 / 3, 0), (0.25,) * 4]
    out = {f"BLEU-{n + 1}": corpus_bleu(refs_tok, hyps_tok, weights=w,
                                        smoothing_function=smooth)
           for n, w in enumerate(weights)}
    out["METEOR"] = float(np.mean([meteor_score(r, h) for r, h in zip(refs_tok, hyps_tok)]))
    scorer = rouge_scorer.RougeScorer(["rougeL"])
    out["ROUGE-L"] = float(np.mean([max(scorer.score(r, h)["rougeL"].fmeasure for r in refs)
                                    for refs, h in zip(references, hypotheses)]))
    out["WER"] = float(np.mean([min(jiwer.wer(r, h if h else "<empty>") for r in refs)
                                for refs, h in zip(references, hypotheses)]))
    return {k: round(float(v), 4) for k, v in out.items()}


# ------------------------------------------------------------------ metrics.csv
def read_rows(path: Path = None) -> list:
    path = path or config.RESULTS_DIR / "metrics.csv"
    if not Path(path).exists():
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def upsert_row(row: dict, path: Path = None) -> list:
    """Insert or replace the row with the same (run, decoding)."""
    path = path or config.RESULTS_DIR / "metrics.csv"
    rows = [r for r in read_rows(path)
            if (r["run"], r["decoding"]) != (row["run"], row["decoding"])]
    rows.append({k: row[k] for k in COLUMNS})
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=COLUMNS)
        w.writeheader()
        w.writerows(rows)
    return rows


def markdown_table(rows: list) -> str:
    head = ["Backbone", "Vocab", "Images", "Epochs", "Decoding"] + METRICS
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        vals = [str(r[k]) for k in ["backbone", "vocab", "images", "epochs", "decoding"]]
        vals += [f"{float(r[m]):.3f}" for m in METRICS]
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines)


def update_readme(rows: list, readme: Path = README) -> bool:
    if not readme.exists():
        return False
    text = readme.read_text(encoding="utf-8")
    if MARK_START not in text or MARK_END not in text:
        return False
    body = (markdown_table(rows) + "\n\n_Generated by `python -m src.evaluate` from "
            "[results/metrics.csv](results/metrics.csv). WER: lower is better._\n\n"
            "![Held-out metrics compared across runs](results/comparison.png)")
    if not rows:
        body = "_No evaluated runs yet. Train and run `python -m src.evaluate`._"
    pre, rest = text.split(MARK_START, 1)
    _, post = rest.split(MARK_END, 1)
    readme.write_text(f"{pre}{MARK_START}\n{body}\n{MARK_END}{post}", encoding="utf-8")
    return True


def report(rows: list):
    from src.plotting import plot_comparison

    if rows:
        plot_comparison(rows, METRICS, config.RESULTS_DIR / "comparison.png")
    update_readme(rows)


# ------------------------------------------------------------------ evaluation
def evaluate(run: str, beam: int = 1, limit: int = None) -> dict:
    from tqdm import tqdm

    from src.caption import Captioner
    from src.data import get_split, load_manifest, strip_tokens
    from src.features import extract_features, feature_path

    cap = Captioner(config.CHECKPOINT_DIR / run)
    cfg = cap.cfg
    _, val_items = get_split(load_manifest(), cfg["num_images"])
    if limit:
        val_items = val_items[:limit]
    extract_features([i["image_path"] for i in val_items], cfg["backbone"])
    refs, hyps = [], []
    for item in tqdm(val_items, desc=f"eval {run}"):
        feats = cap.cached_features(feature_path(item["image_path"], cfg["backbone"]))
        text, _, _ = cap.caption(feats=feats, beam=beam)
        hyps.append(text)
        refs.append([strip_tokens(c) for c in item["captions"]])
    scores = compute_metrics(refs, hyps)
    decoding = "greedy" if beam <= 1 else f"beam{beam}"
    row = {"run": run, "backbone": cfg["backbone"], "vocab": cfg["vocab_size"],
           "images": cfg["num_images"], "epochs": cfg["epochs"], "decoding": decoding,
           **scores}
    config.RESULTS_DIR.mkdir(exist_ok=True)
    with open(config.RESULTS_DIR / f"predictions_{run}_{decoding}.csv", "w", newline="",
              encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["image", "prediction", "reference_1"])
        for item, h, r in zip(val_items, hyps, refs):
            w.writerow([Path(item["image_path"]).name, h, r[0]])
    rows = upsert_row(row)
    report(rows)
    print(f"{run} ({decoding}, {len(val_items)} held-out images): {scores}")
    return row


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run", help="run folder name under checkpoints/")
    p.add_argument("--beam", type=int, default=1, help="1 = greedy")
    p.add_argument("--limit", type=int, help="evaluate only the first N held-out images")
    p.add_argument("--report-only", action="store_true",
                   help="only rebuild comparison.png and the README table")
    a = p.parse_args()
    if a.report_only:
        report(read_rows())
        return
    if not a.run:
        p.error("--run is required unless --report-only is given")
    evaluate(a.run, a.beam, a.limit)


if __name__ == "__main__":
    main()
